    public static Geometry? Get(string? name) =>
        name is not null && Map.TryGetValue(name, out var g) ? g : null;

    // ---------- constructeurs ----------

    private static GeometryGroup Gr(params Geometry[] parts)
    {
        var group = new GeometryGroup();
        foreach (var p in parts) group.Children.Add(p);
        return group;
    }

    private static EllipseGeometry C(double cx, double cy, double r) =>
        new(new System.Windows.Point(cx, cy), r, r);

    private static LineGeometry L(double x1, double y1, double x2, double y2) =>
        new(new System.Windows.Point(x1, y1), new System.Windows.Point(x2, y2));

    private static Geometry Pd(string data) => Geometry.Parse(data);
